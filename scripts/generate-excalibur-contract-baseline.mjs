#!/usr/bin/env node

import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const mirrorArg = args.indexOf("--mirror");
if (mirrorArg >= 0 && !args[mirrorArg + 1]) {
  throw new Error("--mirror requires the canonical generated .mjs path");
}

const candidates = [
  mirrorArg >= 0 ? args[mirrorArg + 1] : undefined,
  process.env.EXCALIBUR_CONTRACT_MIRROR,
  process.env.EXCALIBUR_MONOREPO_ROOT
    ? resolve(process.env.EXCALIBUR_MONOREPO_ROOT, "packages/excalibur-control-contracts/generated/excalibur-control-contracts.mjs")
    : undefined,
  resolve(repositoryRoot, "../excalibur-one-surface-mono/packages/excalibur-control-contracts/generated/excalibur-control-contracts.mjs"),
  resolve(repositoryRoot, "../BenchAGI_Mono_Repo/packages/excalibur-control-contracts/generated/excalibur-control-contracts.mjs"),
].filter(Boolean).map((item) => resolve(String(item)));

let mirrorPath = null;
for (const candidate of candidates) {
  try {
    await access(candidate);
    mirrorPath = candidate;
    break;
  } catch {
    // Try the next explicitly bounded source location.
  }
}
if (!mirrorPath) {
  throw new Error(
    "canonical Excalibur contract mirror not found; set EXCALIBUR_CONTRACT_MIRROR or pass --mirror <path>",
  );
}

const mirror = await import(`${pathToFileURL(mirrorPath).href}?digest=${Date.now()}`);
const requiredExports = [
  "EXCALIBUR_PROTOCOL_VERSION",
  "EXCALIBUR_SCHEMA_VERSION",
  "EXCALIBUR_MANIFEST_VERSION",
  "EXCALIBUR_SIDECAR_MIRROR_DIGEST",
  "V1_CAPABILITY_MANIFEST",
  "V1_ROUTING_PROFILE",
  "canonicalSha256",
];
for (const name of requiredExports) {
  if (mirror[name] === undefined) throw new Error(`canonical mirror is missing ${name}`);
}

const digests = {
  protocol: await mirror.canonicalSha256({ protocolVersion: mirror.EXCALIBUR_PROTOCOL_VERSION }),
  manifest: await mirror.canonicalSha256(mirror.V1_CAPABILITY_MANIFEST),
  routing: await mirror.canonicalSha256(mirror.V1_ROUTING_PROFILE),
};
const capabilities = mirror.V1_CAPABILITY_MANIFEST?.capabilities;
if (!Array.isArray(capabilities)) throw new Error("canonical mirror capability manifest is malformed");
const viewCapabilityIds = capabilities
  .filter((item) => item?.kind === "read")
  .map((item) => item.capabilityId);
const actionCapabilityIds = capabilities
  .filter((item) => item?.kind === "action")
  .map((item) => item.capabilityId);
if (!viewCapabilityIds.every((item) => typeof item === "string")
    || !actionCapabilityIds.every((item) => typeof item === "string")) {
  throw new Error("canonical mirror contains invalid capability identifiers");
}

const baseline = {
  generatorVersion: 1,
  sourceMirrorDigest: mirror.EXCALIBUR_SIDECAR_MIRROR_DIGEST,
  protocolVersion: mirror.EXCALIBUR_PROTOCOL_VERSION,
  schemaVersion: mirror.EXCALIBUR_SCHEMA_VERSION,
  manifestVersion: mirror.EXCALIBUR_MANIFEST_VERSION,
  digests,
  viewCapabilityIds,
  actionCapabilityIds,
};

function render(typescript) {
  const literal = JSON.stringify(baseline, null, typescript ? 2 : 4);
  const gap = typescript ? "\n" : "";
  return `// GENERATED by scripts/generate-excalibur-contract-baseline.mjs from the canonical\n`
    + `// @bench/excalibur-control-contracts sidecar mirror. Do not edit by hand.\n${gap}`
    + `export const EXCALIBUR_CONTRACT_BASELINE = Object.freeze(${literal}${typescript ? " as const" : ""});\n${gap}`
    + `export const EXCALIBUR_EXPECTED_DIGESTS = EXCALIBUR_CONTRACT_BASELINE.digests;\n`
    + `export const EXCALIBUR_VIEW_CAPABILITY_IDS = EXCALIBUR_CONTRACT_BASELINE.viewCapabilityIds;\n`
    + `export const EXCALIBUR_ACTION_CAPABILITY_IDS = EXCALIBUR_CONTRACT_BASELINE.actionCapabilityIds;\n`;
}

const outputs = [
  [resolve(repositoryRoot, "src/v2/excalibur/contract-baseline.ts"), render(true)],
  [resolve(repositoryRoot, "dist/v2/excalibur/contract-baseline.js"), render(false)],
];

let drifted = false;
for (const [outputPath, expected] of outputs) {
  if (checkOnly) {
    const actual = await readFile(outputPath, "utf8").catch(() => "");
    if (actual !== expected) {
      console.error(`Excalibur contract baseline drift: ${outputPath}`);
      drifted = true;
    }
  } else {
    await writeFile(outputPath, expected, { encoding: "utf8", mode: 0o644 });
  }
}
if (drifted) process.exitCode = 1;
else console.log(`Excalibur contract baseline ${checkOnly ? "matches" : "generated from"} ${mirrorPath}`);
